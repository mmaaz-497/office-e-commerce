/** Icons whose shapes read correctly only as solid fills. */
const FILLED: ReadonlySet<IconName> = new Set(["star", "play"]);

export function Icon({
  name,
  className = "h-5 w-5",
  title,
}: {
  name: IconName;
  className?: string;
  /** Supply only when the icon carries meaning no adjacent text already does. */
  title?: string;
}) {
  const filled = FILLED.has(name);

  return (
    <svg
      viewBox="0 0 24 24"
      className={className}
      fill={filled ? "currentColor" : "none"}
      stroke={filled ? "none" : "currentColor"}
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {PATHS[name]}
    </svg>
  );
}
