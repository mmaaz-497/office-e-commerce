import createMiddleware from "next-intl/middleware";
import { NextResponse, type NextRequest } from "next/server";
import { routing } from "@/i18n/routing";
import { SESSION_COOKIE_NAME, verifySessionToken } from "@/infrastructure/auth/session";

const intlMiddleware = createMiddleware(routing);

/**
 * Defence in depth for /admin/** (R-010, FR-055) — every admin action and
 * page still calls requireAdminSession() itself, since middleware does not
 * run for every invocation path. Runs under the Node.js runtime (not Edge)
 * so it can share verifySessionToken with the server-action guard instead of
 * reimplementing verification twice. Pages without a valid session are
 * redirected to /admin/login; /admin/api/* gets 401 JSON instead.
 */
export default function middleware(request: NextRequest) {
  const { pathname } = request.nextUrl;

  if (pathname.startsWith("/admin")) {
    if (pathname === "/admin/login") {
      return NextResponse.next();
    }
    const token = request.cookies.get(SESSION_COOKIE_NAME)?.value;
    if (!verifySessionToken(token)) {
      // /admin/api/* is called with fetch (the image upload, R-301): a
      // redirect would hand the caller the login page's HTML with a 200, so
      // it gets a 401 JSON it can act on. Pages still redirect to sign-in.
      if (pathname.startsWith("/admin/api/")) {
        return NextResponse.json({ error: "unauthorized" }, { status: 401 });
      }
      return NextResponse.redirect(new URL("/admin/login", request.url));
    }
    return NextResponse.next();
  }

  return intlMiddleware(request);
}

export const config = {
  runtime: "nodejs",
  // The documented next-intl matcher, '/((?!api|trpc|_next|_vercel|.*\\..*).*)',
  // excludes API and static paths but would still match /admin. The admin area
  // is deliberately non-localised (spec, admin routes section), so `admin` must
  // be excluded explicitly here — verified by T008's AC that /admin/login is
  // served with no locale prefix and is never redirected. See research.md R-002.
  // The second pattern brings /admin/** into the middleware invocation set so
  // the guard above actually runs for it (R-010).
  // `icon` is the favicon generated by src/app/icon.tsx. Its URL has no file
  // extension, so the `.*\\..*` clause does not catch it: without this
  // exclusion next-intl redirects /icon to /id/icon, which 404s on every page
  // load — and in dev, that 404 compiles the [...rest] route as well.
  matcher: ["/((?!api|trpc|_next|_vercel|admin|icon|.*\\..*).*)", "/admin/:path*"],
};
